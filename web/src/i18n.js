// "2026-11-30" → "նոյեմբերի 30" / "30 ноября" / "30 November"
export function fmtDate(iso, lang) {
  if (!iso) return '';
  const [, m, d] = iso.slice(0, 10).split('-').map(Number);
  if (lang === 'hy') return `${MONTHS.hy.gen[m - 1]} ${d || 1}`;
  if (lang === 'ru') return `${d || 1} ${MONTHS.ru.gen[m - 1]}`;
  return `${d || 1} ${MONTHS.en.nom[m - 1]}`;
}

// "2026-11" → "նոյեմբեր" / "ноябрь" / "November"
export function fmtMonth(iso, lang) {
  if (!iso) return '';
  const m = Number(iso.split('-')[1]);
  const name = (MONTHS[lang] || MONTHS.en).nom[m - 1];
  return lang === 'en' ? name : name[0].toUpperCase() + name.slice(1);
}

// SQLite UTC timestamp → local "14:05" today, otherwise a date.
export function fmtWhen(sqlTs, lang) {
  if (!sqlTs) return '';
  const d = new Date(`${sqlTs.replace(' ', 'T')}Z`);
  const now = new Date();
  if (d.toDateString() === now.toDateString()) {
    return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
  }
  const iso = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  return fmtDate(iso, lang);
}

export function fmtAmount(amount, currency) {
  if (amount == null) return '';
  return `${new Intl.NumberFormat('en-US').format(amount).replace(/,/g, ' ')}${currency ? ` ${currency}` : ''}`;
}

export function detectInitialLang() {
  const nav = (navigator.language || '').toLowerCase();
  if (nav.startsWith('ru')) return 'ru';
  if (nav.startsWith('en')) return 'en';
  return 'hy';
}
